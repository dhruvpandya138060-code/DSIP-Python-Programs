def frequency_filter(img, filter_type, cutoff=30, order=2):

    rows, cols = img.shape

    # Apply Fourier Transform
    dft = np.fft.fft2(img)
    dft_shift = np.fft.fftshift(dft)

    # Create frequency distance matrix
    u = np.arange(rows) - rows // 2
    v = np.arange(cols) - cols // 2
    U, V = np.meshgrid(v, u)
    D = np.sqrt(U**2 + V**2)

    # Create frequency masks
    if filter_type == "gaussian":
        mask = np.exp(-(D**2) / (2 * cutoff**2))

    elif filter_type == "butterworth":
        mask = 1 / (1 + (D / cutoff)**(2 * order))

    # Apply filter
    filtered = dft_shift * mask

    # Inverse Fourier Transform
    result = np.fft.ifft2(
        np.fft.ifftshift(filtered)
    )

    result = np.abs(result)

    return np.uint8(
        np.clip(result, 0, 255)
    )


for filename in uploaded.keys():

    img = cv2.imread(
        filename, cv2.IMREAD_GRAYSCALE
    )

    if img is None:
        print("Image not found:", filename)
        continue

    # Frequency-domain smoothing
    gaussian = frequency_filter(
        img, "gaussian", 30
    )

    butterworth = frequency_filter(
        img, "butterworth", 30, 2
    )

    # FFT for High-Boost Sharpening
    rows, cols = img.shape

    dft = np.fft.fft2(gaussian)
    dft_shift = np.fft.fftshift(dft)

    u = np.arange(rows) - rows // 2
    v = np.arange(cols) - cols // 2
    U, V = np.meshgrid(v, u)

    D = np.sqrt(U**2 + V**2)

    # Gaussian high-boost mask
    low_mask = np.exp(
        -(D**2) / (2 * 30**2)
    )

    high_boost = 1 + 1.5 * (1 - low_mask)

    # Apply high-boost filter
    sharpened_freq = dft_shift * high_boost

    sharpened = np.fft.ifft2(
        np.fft.ifftshift(sharpened_freq)
    )

    sharpened = np.abs(sharpened)

    sharpened = cv2.normalize(
        sharpened, None, 0, 255,
        cv2.NORM_MINMAX
    ).astype(np.uint8)

    # Boundary extraction using Canny
    edges = cv2.Canny(
        sharpened, 50, 150
    )

    # Display results
    titles = [
        "Original Image",
        "Gaussian Low Pass",
        "Butterworth Low Pass",
        "High Boost Sharpening",
        "Boundary Extraction"
    ]

    images = [
        img, gaussian, butterworth,
        sharpened, edges
    ]

    plt.figure(figsize=(15, 9))

    for i in range(5):
        plt.subplot(2, 3, i + 1)
        plt.imshow(images[i], cmap='gray')
        plt.title(titles[i])
        plt.axis('off')

    plt.suptitle(
        "OPE 10 - Frequency Domain Processing"
    )

    plt.tight_layout()
    plt.show()

    # Quantitative analysis
    print("\nImage:", filename)
    print("--------------------------------")

    for title, result in [
        ("Original", img),
        ("Gaussian", gaussian),
        ("Butterworth", butterworth),
        ("Sharpened", sharpened)
    ]:
        sharpness = cv2.Laplacian(
            result, cv2.CV_64F
        ).var()

        contrast = np.std(result)

        print(title)
        print("Standard Deviation:", round(contrast, 2))
        print("Laplacian Variance:", round(sharpness, 2))

    print("Edge Pixel Count:", np.count_nonzero(edges))

    # Save processed images
    name = os.path.splitext(filename)[0]

    cv2.imwrite(
        f"OPE10_Results/{name}_Gaussian.png",
        gaussian
    )

    cv2.imwrite(
        f"OPE10_Results/{name}_Butterworth.png",
        butterworth
    )

    cv2.imwrite(
        f"OPE10_Results/{name}_Sharpened.png",
        sharpened
    )

    cv2.imwrite(
        f"OPE10_Results/{name}_Boundaries.png",
        edges
    )

