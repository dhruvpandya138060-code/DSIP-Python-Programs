import cv2
import numpy as np
import matplotlib.pyplot as plt
from google.colab import files
import os

# Upload OPE7 images
uploaded = files.upload()

os.makedirs("OPE9_Results", exist_ok=True)

for filename in uploaded.keys():

    # Read image in grayscale
    img = cv2.imread(filename, cv2.IMREAD_GRAYSCALE)

    if img is None:
        print("Image not found:", filename)
        continue

    # Smoothing Techniques
    average = cv2.blur(img, (5, 5))

    gaussian = cv2.GaussianBlur(
        img, (5, 5), 1.2
    )

    median = cv2.medianBlur(img, 5)

    bilateral = cv2.bilateralFilter(
        img, 9, 75, 75
    )

    # Laplacian Sharpening
    kernel = np.array([
        [0, -1, 0],
        [-1, 5, -1],
        [0, -1, 0]
    ])

    sharpened = cv2.filter2D(
        img, -1, kernel
    )

    # Unsharp Masking
    blurred = cv2.GaussianBlur(
        img, (5, 5), 1.0
    )

    unsharp = cv2.addWeighted(
        img, 1.5, blurred, -0.5, 0
    )

    # Display Results
    titles = [
        "Original Image",
        "Average Filter",
        "Gaussian Filter",
        "Median Filter",
        "Bilateral Filter",
        "Laplacian Sharpening",
        "Unsharp Masking"
    ]

    images = [
        img, average, gaussian, median,
        bilateral, sharpened, unsharp
    ]

    plt.figure(figsize=(15, 10))

    for i in range(7):
        plt.subplot(3, 3, i + 1)
        plt.imshow(images[i], cmap='gray')
        plt.title(titles[i])
        plt.axis('off')

    plt.suptitle("OPE 9 - Smoothing and Sharpening")
    plt.tight_layout()
    plt.show()

    # Save processed images
    name = os.path.splitext(filename)[0]

    cv2.imwrite(
        f"OPE9_Results/{name}_Average.png", average
    )

    cv2.imwrite(
        f"OPE9_Results/{name}_Gaussian.png", gaussian
    )

    cv2.imwrite(
        f"OPE9_Results/{name}_Median.png", median
    )

    cv2.imwrite(
        f"OPE9_Results/{name}_Bilateral.png", bilateral
    )

    cv2.imwrite(
        f"OPE9_Results/{name}_Sharpened.png", sharpened
    )

    cv2.imwrite(
        f"OPE9_Results/{name}_Unsharp.png", unsharp
    )

print("All images processed successfully!")
print("Results saved in OPE9_Results folder.")