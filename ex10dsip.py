import cv2
import numpy as np
import matplotlib.pyplot as plt
from google.colab import files

# 1. Upload image
uploaded = files.upload()
image_path = list(uploaded.keys())[0]

# 2. Read image in grayscale
img = cv2.imread(image_path, 0)

# 3. Fourier Transform
F = np.fft.fftshift(np.fft.fft2(img))
M, N = img.shape

# 4. Create frequency distance matrix
u, v = np.meshgrid(
    np.arange(N) - N//2,
    np.arange(M) - M//2
)
D = np.sqrt(u**2 + v**2)

# 5. Create Low-Pass and High-Pass Filters
LPF = D < 30
HPF = D >= 30

# 6. Apply filters
smooth = np.abs(
    np.fft.ifft2(np.fft.ifftshift(F * LPF))
)

high_pass = np.abs(
    np.fft.ifft2(np.fft.ifftshift(F * HPF))
)

sharp = np.clip(
    img.astype(float) + high_pass, 0, 255
)

# 7. Display output images
plt.figure(figsize=(12, 4))

plt.subplot(1, 3, 1)
plt.imshow(img, cmap='gray')
plt.title('Original Image')
plt.axis('off')

plt.subplot(1, 3, 2)
plt.imshow(smooth, cmap='gray')
plt.title('LPF - Smoothing')
plt.axis('off')

plt.subplot(1, 3, 3)
plt.imshow(sharp, cmap='gray')
plt.title('HPF - Sharpening')
plt.axis('off')

plt.show()