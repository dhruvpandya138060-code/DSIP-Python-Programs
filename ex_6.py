# EXPERIMENT 6: FIR Filter Design Using Windowing Method

import numpy as np
import matplotlib.pyplot as plt
from scipy.signal import firwin, freqz

# Step 1: Define parameters
Fs = 10000       # Sampling frequency = 10 kHz
N = 31           # Number of filter taps
nyquist = Fs / 2

print("Sampling Frequency:", Fs, "Hz")
print("Nyquist Frequency:", nyquist, "Hz")
print("Number of Taps:", N)
print("Filter Order:", N - 1)

# Step 2: Design the four FIR filters
# LPF and HPF use the specified 3 kHz cutoff.
lpf = firwin(N, cutoff=3000, window="hann",
             pass_zero="lowpass", fs=Fs)

hpf = firwin(N, cutoff=3000, window="hann",
             pass_zero="highpass", fs=Fs)

# IMPORTANT:
# 6 kHz exceeds the 5 kHz Nyquist frequency.
# Use 4 kHz for the valid BPF/BSF demonstration.
low_cut = 3000
high_cut = 4000

bpf = firwin(N, cutoff=[low_cut, high_cut],
             window="hann", pass_zero="bandpass", fs=Fs)

bsf = firwin(N, cutoff=[low_cut, high_cut],
             window="hann", pass_zero="bandstop", fs=Fs)

filters = {
    "Low-Pass Filter (3 kHz)": lpf,
    "High-Pass Filter (3 kHz)": hpf,
    "Band-Pass Filter (3-4 kHz)": bpf,
    "Band-Stop Filter (3-4 kHz)": bsf
}

# Step 3: Display filter coefficients
for name, coefficients in filters.items():
    print("\n", name)
    print("Filter coefficients:")
    print(np.round(coefficients, 6))

# Step 4: Plot magnitude and phase responses
for name, coefficients in filters.items():
    f, H = freqz(coefficients, worN=4096, fs=Fs)

    magnitude_db = 20 * np.log10(
        np.maximum(np.abs(H), 1e-10)
    )

    phase = np.unwrap(np.angle(H))

    fig, ax = plt.subplots(2, 1, figsize=(10, 7))

    ax[0].plot(f, magnitude_db)
    ax[0].set_title(name + " - Magnitude Response")
    ax[0].set_xlabel("Frequency (Hz)")
    ax[0].set_ylabel("Magnitude (dB)")
    ax[0].grid(True)
    ax[0].set_xlim(0, nyquist)

    ax[1].plot(f, phase)
    ax[1].set_title(name + " - Phase Response")
    ax[1].set_xlabel("Frequency (Hz)")
    ax[1].set_ylabel("Phase (radians)")
    ax[1].grid(True)
    ax[1].set_xlim(0, nyquist)

    plt.tight_layout()
    plt.show()

print("\nAll four FIR filters designed successfully.")
print("Note: BPF and BSF use 3 kHz and 4 kHz.")