import cv2
import numpy as np
import matplotlib.pyplot as plt
from google.colab import files
import os

# Upload input images
uploaded = files.upload()

os.makedirs("OPE6_Results", exist_ok=True)

for filename in uploaded.keys():

    img = cv2.imread(filename, cv2.IMREAD_GRAYSCALE)

    if img is None:
        print("Image not found:", filename)
        continue

    # Convert image into binary form
    _, binary = cv2.threshold(
        img, 0, 255,
        cv2.THRESH_BINARY + cv2.THRESH_OTSU
    )

    # Select foreground polarity using border pixels
    border = np.concatenate([
        binary[0, :], binary[-1, :],
        binary[:, 0], binary[:, -1]
    ])

    if np.mean(border == 255) > 127:
        binary = cv2.bitwise_not(binary)

    # Create 3x3 structuring element
    kernel = np.ones((3, 3), np.uint8)

    # Apply Opening to remove small bright noise
    opening = cv2.morphologyEx(
        binary, cv2.MORPH_OPEN, kernel
    )

    # Apply Closing to fill narrow dark cracks
    closing = cv2.morphologyEx(
        opening, cv2.MORPH_CLOSE, kernel
    )

    # Display results
    titles = [
        "Original Image",
        "Binary Image",
        "After Opening",
        "After Closing"
    ]

    images = [img, binary, opening, closing]

    plt.figure(figsize=(12, 8))

    for i in range(4):
        plt.subplot(2, 2, i + 1)
        plt.imshow(images[i], cmap='gray')
        plt.title(titles[i])
        plt.axis('off')

    plt.suptitle("OPE 6 - Morphological Operations")
    plt.tight_layout()
    plt.show()

    # Save processed images
    name = os.path.splitext(filename)[0]

    cv2.imwrite(
        f"OPE6_Results/{name}_Binary.png", binary
    )

    cv2.imwrite(
        f"OPE6_Results/{name}_Opening.png", opening
    )

    cv2.imwrite(
        f"OPE6_Results/{name}_Closing.png", closing
    )

print("Morphological operations completed successfully!")