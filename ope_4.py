# Q3(a): Low-Pass Filtering at Three Cutoff Frequencies

import librosa
import librosa.display
import numpy as np
import matplotlib.pyplot as plt
import soundfile as sf
from scipy.signal import butter, sosfiltfilt
from google.colab import files
from IPython.display import Audio, display

# Step 1: Upload the MP3 file
uploaded = files.upload()
filename = next(iter(uploaded.keys()))

# Step 2: Load the audio
y, sr = librosa.load(filename, sr=None, mono=True)

print("Sample Rate:", sr, "Hz")
print("Duration:", round(len(y) / sr, 2), "seconds")

# Step 3: Design a Butterworth low-pass filter
def lowpass_filter(data, cutoff, fs, order=6):
    nyquist = fs / 2

    if cutoff <= 0 or cutoff >= nyquist:
        raise ValueError("Cutoff must be between 0 and Nyquist frequency.")

    sos = butter(
        order, cutoff, btype="lowpass",
        fs=fs, output="sos"
    )
    return sosfiltfilt(sos, data)

# Step 4: Apply three cutoff frequencies
cutoff_frequencies = [500, 1500, 3000]
filtered_signals = {}

for cutoff in cutoff_frequencies:
    filtered = lowpass_filter(y, cutoff, sr)
    filtered_signals[cutoff] = filtered

    output_file = f"lowpass_{cutoff}Hz.wav"
    sf.write(output_file, filtered, sr)

    print(f"\nFiltered audio with cutoff = {cutoff} Hz")
    display(Audio(filtered, rate=sr))

# Step 5: Plot the original and filtered spectrograms
signals = [("Original Audio", y)] + [
    (f"Low-Pass Filter: {fc} Hz", filtered_signals[fc])
    for fc in cutoff_frequencies
]

fig, axes = plt.subplots(4, 1, figsize=(12, 14))

for ax, (title, signal) in zip(axes, signals):
    D = librosa.stft(signal, n_fft=2048)
    D_db = librosa.amplitude_to_db(np.abs(D), ref=np.max)

    librosa.display.specshow(
        D_db, sr=sr, x_axis="time", y_axis="linear",
        cmap="viridis", ax=ax
    )
    ax.set_ylim(0, min(10000, sr / 2))
    ax.set_title(title)
    ax.set_xlabel("Time (seconds)")
    ax.set_ylabel("Frequency (Hz)")

plt.tight_layout()
plt.show()

# Step 6: Plot the frequency response of the filters
from scipy.signal import sosfreqz

plt.figure(figsize=(10, 5))

for cutoff in cutoff_frequencies:
    sos = butter(6, cutoff, btype="lowpass", fs=sr, output="sos")
    freq, response = sosfreqz(sos, worN=2048, fs=sr)
    magnitude_db = 20 * np.log10(np.maximum(np.abs(response), 1e-8))
    plt.plot(freq, magnitude_db, label=f"{cutoff} Hz")

plt.title("Frequency Responses of Low-Pass Filters")
plt.xlabel("Frequency (Hz)")
plt.ylabel("Magnitude (dB)")
plt.xlim(0, min(8000, sr / 2))
plt.ylim(-80, 5)
plt.grid(True)
plt.legend()
plt.show()

# Step 7: Download the filtered WAV files
for cutoff in cutoff_frequencies:
    files.download(f"lowpass_{cutoff}Hz.wav")

# Q3(b): Vocal-Focused and Background-Reduced Audio

import numpy as np
import soundfile as sf
import subprocess
from scipy.signal import butter, sosfiltfilt
from IPython.display import Audio, display
from google.colab import files

# Step 1: Load the audio
# If Part (a) was run, y and sr already exist.
# Otherwise, upload the MP3 file.

try:
    y, sr
except NameError:
    uploaded = files.upload()
    filename = next(iter(uploaded.keys()))
    y, sr = librosa.load(filename, sr=None, mono=True)

# Step 2: Design a band-pass filter
def bandpass_filter(data, lowcut, highcut, fs, order=6):
    if not (0 < lowcut < highcut < fs / 2):
        raise ValueError("Cutoffs must be between 0 and Nyquist.")

    sos = butter(
        order, [lowcut, highcut],
        btype="bandpass", fs=fs, output="sos"
    )
    return sosfiltfilt(sos, data)

# Step 3: Design a band-stop filter
def bandstop_filter(data, lowcut, highcut, fs, order=6):
    if not (0 < lowcut < highcut < fs / 2):
        raise ValueError("Cutoffs must be between 0 and Nyquist.")

    sos = butter(
        order, [lowcut, highcut],
        btype="bandstop", fs=fs, output="sos"
    )
    return sosfiltfilt(sos, data)

# Step 4: Process the audio
# Band-pass: emphasizes vocal-related frequencies
vocal_focused = bandpass_filter(y, 300, 3400, sr)

# Band-stop: attenuates the selected vocal-related range
background_focused = bandstop_filter(y, 300, 3400, sr)

# Step 5: Normalize safely to avoid clipping
def normalize_audio(signal):
    peak = np.max(np.abs(signal))
    if peak > 0:
        return 0.95 * signal / peak
    return signal

vocal_focused = normalize_audio(vocal_focused)
background_focused = normalize_audio(background_focused)

# Step 6: Save intermediate WAV files
sf.write("vocal_focused.wav", vocal_focused, sr)
sf.write("background_focused.wav", background_focused, sr)

# Step 7: Convert WAV files to MP3 using FFmpeg
def convert_to_mp3(input_file, output_file):
    subprocess.run([
        "ffmpeg", "-y", "-i", input_file,
        "-codec:a", "libmp3lame", "-b:a", "192k",
        output_file
    ], check=True, stdout=subprocess.DEVNULL,
       stderr=subprocess.PIPE)

convert_to_mp3("vocal_focused.wav", "vocal_focused.mp3")
convert_to_mp3("background_focused.wav", "background_focused.mp3")

print("Vocal-focused audio:")
display(Audio(vocal_focused, rate=sr))

print("Background-focused audio:")
display(Audio(background_focused, rate=sr))

