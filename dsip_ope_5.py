import cv2
import numpy as np
import matplotlib.pyplot as plt
from google.colab import files
import os

# Upload OPE7 images
uploaded = files.upload()

os.makedirs("OPE5_Results", exist_ok=True)

for filename in uploaded.keys():

    # Read image in grayscale
    img = cv2.imread(filename, cv2.IMREAD_GRAYSCALE)

    if img is None:
        print("Image not found:", filename)
        continue

    # Apply Median Filters
    median3 = cv2.medianBlur(img, 3)
    median5 = cv2.medianBlur(img, 5)
    median7 = cv2.medianBlur(img, 7)

    # Apply Bilateral Filter
    bilateral = cv2.bilateralFilter(img, 9, 75, 75)

    # Display all results
    titles = ["Original Image", "Median 3x3",
              "Median 5x5", "Median 7x7",
              "Bilateral Filter"]

    images = [img, median3, median5, median7, bilateral]

    plt.figure(figsize=(14, 8))

    for i in range(5):
        plt.subplot(2, 3, i + 1)
        plt.imshow(images[i], cmap='gray')
        plt.title(titles[i])
        plt.axis('off')

    plt.suptitle("OPE 5 - Non-Linear Filtering")
    plt.tight_layout()
    plt.show()

    # Save filtered images
    name = os.path.splitext(filename)[0]

    cv2.imwrite("OPE5_Results/" + name + "_Median3.png", median3)
    cv2.imwrite("OPE5_Results/" + name + "_Median5.png", median5)
    cv2.imwrite("OPE5_Results/" + name + "_Median7.png", median7)
    cv2.imwrite("OPE5_Results/" + name + "_Bilateral.png", bilateral)

print("All images processed successfully!")
print("Results saved in OPE5_Results folder.")